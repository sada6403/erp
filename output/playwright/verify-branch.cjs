const { chromium } = require('C:/Users/USER/AppData/Local/npm-cache/_npx/31e32ef8478fbf80/node_modules/playwright')
const assert = require('node:assert/strict')
const fs = require('fs')
const path = require('path')
;(async () => {
  const browser = await chromium.connectOverCDP('http://127.0.0.1:9337')
  const page = browser.contexts()[0].pages()[0]
  if (await page.getByRole('button', { name: 'Close', exact: true }).count()) await page.getByRole('button', { name: 'Close', exact: true }).first().click()
  console.log(await page.locator('main').ariaSnapshot())
  await page.getByRole('button', { name: 'Create Branch', exact: true }).last().click()
  await page.getByPlaceholder('e.g. Nimal Perera').fill('Furniture QA Manager')
  await page.getByPlaceholder('manager@company.com').fill('furniture-qa@example.invalid')
  await page.getByRole('button', { name: 'Next', exact: true }).click()
  assert.equal(await page.getByPlaceholder('e.g. Kandy Branch').inputValue(), 'CHAVAKACHERY')
  await page.getByPlaceholder('e.g. KDY').fill('CHAVAQA')
  await page.getByPlaceholder('e.g. 1001').fill('476813')
  await page.getByRole('button', { name: 'Next', exact: true }).click()
  await page.getByRole('button', { name: 'Create Branch', exact: true }).last().click()
  await page.getByRole('heading', { name: 'Branch Created', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Done', exact: true }).click()
  await page.getByRole('heading', { name: 'CHAVAKACHERY', exact: true }).waitFor()
  assert.equal(await page.getByRole('heading', { name: 'Pending Furniture Branch Stock' }).count(), 0)
  const state = await page.evaluate(() => window.furnitureQA.inspect())
  assert.deepEqual(state.stock.filter(row => row.branch_name === 'CHAVAKACHERY').map(row=>row.quantity).sort((a,b)=>a-b), [1,15,19])
  assert.equal(state.pending.filter(row => row.status === 'pending').length, 0)
  assert.equal(state.movements.length, 4)
  const branch = state.branches.find(row => row.name === 'CHAVAKACHERY')
  const repeat = await page.evaluate(id => window.api.admin.branches.applyPendingStocks('CHAVAKACHERY', id), branch.id)
  assert.equal(repeat.success, true)
  assert.equal(repeat.data.appliedCount, 0)
  await page.screenshot({ path: path.join(__dirname, 'branch-created.png') })
  const restrictions = []
  for (const type of ['retail', 'supermarket']) {
    await page.evaluate(type => window.furnitureQA.businessType(type), type)
    const list = await page.evaluate(() => window.api.admin.branches.getPendingStocks())
    const imported = await page.evaluate(() => window.api.products.importExcel())
    assert.equal(list.success, false)
    assert.equal(imported.success, false)
    assert.match(imported.error, /only for furniture/)
    restrictions.push({ type, pendingRejected: !list.success, importRejected: !imported.success })
  }
  await page.evaluate(() => window.furnitureQA.businessType('furniture'))
  const finalState = await page.evaluate(() => window.furnitureQA.inspect())
  assert.deepEqual(finalState, state)
  fs.writeFileSync(path.join(__dirname, 'verified-branch.json'), JSON.stringify({ state, repeat, restrictions }, null, 2))
  console.log('PASS: pending branch prefill, real branch creation, automatic stock application, pending clearance, repeat prevention, retail/supermarket restrictions')
  await browser.close()
})().catch(error => { console.error(error); process.exit(1) })
