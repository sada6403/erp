const { chromium } = require('C:/Users/USER/AppData/Local/npm-cache/_npx/31e32ef8478fbf80/node_modules/playwright')
const assert = require('node:assert/strict')
const fs = require('fs')
const path = require('path')
;(async () => {
  const browser = await chromium.connectOverCDP('http://127.0.0.1:9337')
  const page = browser.contexts()[0].pages()[0]
  await page.getByRole('button', { name: 'Import CSV / Excel', exact: true }).click()
  await page.getByRole('button', { name: 'Select File & Import', exact: true }).click()
  await page.getByRole('heading', { name: /Import Summary/ }).waitFor()
  const state = await page.evaluate(() => window.furnitureQA.inspect())
  assert.equal(state.products.length, 3)
  assert.deepEqual(state.pending.map(row => row.quantity).sort((a,b)=>a-b), [1,15,19])
  assert.equal(state.stock.find(row => row.branch_name === 'Main Branch').quantity, 2)
  assert.equal(state.products.find(row => row.name === 'BED').selling_price, 36900)
  await page.screenshot({ path: path.join(__dirname, 'import-summary.png') })
  await page.getByRole('button', { name: 'Close', exact: true }).last().click()
  await page.goto(page.url().split('#')[0] + '#/admin/branches')
  await page.getByRole('heading', { name: 'Pending Furniture Branch Stock' }).waitFor()
  assert.match(await page.locator('main').innerText(), /CHAVAKACHERY.*3 items.*35 units/)
  fs.writeFileSync(path.join(__dirname, 'pending-branches.yml'), await page.locator('body').ariaSnapshot())
  await page.screenshot({ path: path.join(__dirname, 'pending-branches.png') })
  fs.writeFileSync(path.join(__dirname, 'verified-import.json'), JSON.stringify(state, null, 2))
  console.log('PASS: Excel quantities, prices, duplicate-code descriptions, existing-branch stock and pending branch summary')
  await browser.close()
})().catch(error => { console.error(error); process.exit(1) })
