const {chromium}=require('C:/Users/USER/AppData/Local/npm-cache/_npx/31e32ef8478fbf80/node_modules/playwright')
const assert=require('node:assert/strict')
const fs=require('node:fs')
;(async()=>{
 const browser=await chromium.connectOverCDP('http://127.0.0.1:9337',{timeout:15000})
 const page=browser.contexts()[0].pages().find(p=>p.url().includes('5173'))
 console.log('Initial UI:',(await page.locator('body').ariaSnapshot()).slice(0,700))
 await page.locator('nav').getByRole('link',{name:'Stock Purchases & Bills',exact:true}).click()
 await page.getByRole('heading',{name:'Stock Purchases & Bills',exact:true}).waitFor()
 await page.getByRole('button',{name:/2\. Add Received Stock Directly/}).click()
 await page.getByRole('heading',{name:'Add Received Stock Directly',exact:true}).waitFor()
 assert.equal(await page.getByRole('button',{name:'Save & Receive Stock',exact:true}).isDisabled(),true)
 await page.getByText('Supplier bill (PDF / image) * Required',{exact:true}).waitFor()
 await page.screenshot({path:'output/playwright/mandatory-supplier-bill-direct.png'})
 await page.getByRole('button',{name:'Close',exact:true}).click()
 await page.getByRole('button',{name:/1\. Order from Supplier/}).click()
 await page.getByRole('heading',{name:'New Purchase Order',exact:true}).waitFor()
 assert.equal(await page.getByRole('button',{name:'Create Purchase Order',exact:true}).isDisabled(),true)
 await page.getByRole('button',{name:'Close',exact:true}).click()
 await page.getByRole('button',{name:'Supplier Bills',exact:true}).click()
 await page.getByRole('columnheader',{name:'Uploaded At',exact:true}).waitFor()
 await page.getByRole('columnheader',{name:'Uploaded By',exact:true}).waitFor()
 const history=await page.evaluate(()=>window.api.purchases.billHistory({}))
 assert.equal(history.success,true,history.error)
 console.log('Saved bills:',history.data.rows.map(r=>({file:r.original_name,supplier:r.supplier_name,invoice:r.supplier_invoice_number,uploaded_at:r.uploaded_at,uploaded_by:r.uploaded_by_name})))
 if(history.data.rows.length){
  const saved=history.data.rows[0]
  const filtered=await page.evaluate(row=>window.api.purchases.billHistory({supplier_id:row.supplier_id,uploaded_by:row.uploaded_by,search:row.original_name,file_type:row.mime_type==='application/pdf'?'pdf':'image'}),saved)
  assert.equal(filtered.success,true,filtered.error)
  assert.ok(filtered.data.rows.some(row=>row.id===saved.id))
  await page.getByRole('button',{name:'Purchase Details',exact:true}).first().click()
  await page.getByText('Uploaded ',{exact:false}).last().waitFor()
  await page.screenshot({path:'output/playwright/supplier-bill-upload-details.png'})
  await page.getByRole('button',{name:'Close',exact:true}).first().click()
 }
 await page.getByRole('textbox',{name:'Search purchase history',exact:true}).fill('NO-MATCH-SUPPLIER-BILL')
 await page.getByText('No uploaded bills match these filters.',{exact:true}).waitFor()
 await page.getByRole('textbox',{name:'Search purchase history',exact:true}).fill('')
 await page.getByRole('textbox',{name:'Uploaded from',exact:true}).waitFor()
 await page.getByRole('combobox',{name:'Uploaded by',exact:true}).waitFor()
 await page.getByRole('combobox',{name:'Bill file type',exact:true}).waitFor()
 await page.screenshot({path:'output/playwright/supplier-bill-history-filters.png'})
 fs.writeFileSync('output/playwright/supplier-bill-history-filters.yml',await page.locator('main').ariaSnapshot())
 console.log('PASS: both forms require bills; live history shows supplier, invoice, uploader/time, filters and file details. No purchase records created.')
 await browser.close()
})().catch(e=>{console.error(e.message);process.exit(1)})
