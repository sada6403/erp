const { chromium } = require('C:/Users/USER/AppData/Local/npm-cache/_npx/31e32ef8478fbf80/node_modules/playwright')
const fs = require('node:fs')
const path = require('node:path')
const dir = path.resolve('output/manual/screens')
fs.mkdirSync(dir, { recursive: true })
;(async () => {
  const browser = await chromium.connectOverCDP('http://127.0.0.1:9337', { timeout: 5000 })
  const page = browser.contexts()[0].pages().find(p => p.url().includes('5173'))
  if (!page) throw new Error('Development page unavailable')
  const originalUrl = page.url()
  const state = await page.evaluate(async () => {
    const { useCartStore } = await import('/src/store/cartStore.ts')
    return { cart: useCartStore.getState().items.length, forms: document.querySelectorAll('h2').length }
  })
  if (state.cart || state.forms) { await browser.close(); throw new Error('Existing work open; retained screenshots will be used') }
  console.log((await page.locator('body').ariaSnapshot()).slice(0, 450))
  const nav = page.locator('nav')
  await nav.getByRole('link', { name: 'Stock Purchases & Bills', exact: true }).click()
  await page.getByRole('heading', { name: 'Stock Purchases & Bills', exact: true }).waitFor()
  const box = await page.locator('main').boundingBox()
  await page.screenshot({ path: path.join(dir, 'purchase-options.png'), clip: { ...box, height: Math.min(box.height, 310) } })
  await page.getByRole('button', { name: /2\. Add Received Stock Directly/ }).click()
  const direct = page.getByRole('heading', { name: 'Add Received Stock Directly', exact: true })
  await direct.waitFor()
  await direct.locator('..').locator('..').screenshot({ path: path.join(dir, 'direct-entry.png') })
  await page.getByRole('button', { name: 'Close', exact: true }).click()
  await page.getByRole('button', { name: 'Supplier Bills', exact: true }).click()
  await page.getByRole('columnheader', { name: 'Uploaded At', exact: true }).waitFor()
  await page.locator('main').screenshot({ path: path.join(dir, 'bill-history.png') })
  const details = page.getByRole('button', { name: 'Purchase Details', exact: true })
  if (await details.count()) {
    await details.first().click()
    const panel = page.getByText('Supplier Invoice & Payment', { exact: true }).locator('..')
    await panel.screenshot({ path: path.join(dir, 'bill-details.png') })
    await page.getByRole('button', { name: 'Close', exact: true }).first().click()
  }
  await nav.getByRole('link', { name: 'Stock & Profit', exact: true }).click()
  await page.getByRole('heading', { name: 'Stock & Profit', exact: true }).waitFor()
  await page.locator('main').screenshot({ path: path.join(dir, 'stock-profit.png') })
  await nav.getByRole('link', { name: 'Owner Investments', exact: true }).click()
  await page.getByRole('heading', { name: 'Owner Investments', exact: true }).waitFor()
  await page.locator('main').screenshot({ path: path.join(dir, 'investments.png') })
  await page.goto(originalUrl)
  await browser.close()
  console.log('Captured current read-only manual screenshots; no business records created')
})().catch(e => { console.log(e.message); process.exitCode = 0 })
